def main() -> None:
    seen: set[str] = set()
    rows = []

    for index, (
        name,
        label,
        ftype,
        group_index,
        required,
        options,
        placeholder,
        description,
        unit,
    ) in enumerate(FIELDS):
        if name in seen:
            raise SystemExit(f"Дублирующееся имя поля: {name}")
        seen.add(name)

        if ";" in "".join([label, placeholder, description, unit, *options]):
            raise SystemExit(f"Символ ';' недопустим в значениях поля {name}")

        rows.append(
            {
                "order": (index + 1) * 10,
                "name": name,
                "label": label,
                "type": ftype,
                "group": GROUPS[group_index],
                "required": "true" if required else "false",
                "options": OPTION_SEPARATOR.join(options),
                "placeholder": placeholder,
                "description": description,
                "unit": unit,
            }
        )

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)

    with OUTPUT.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(
            handle,
            fieldnames=[
                "order",
                "name",
                "label",
                "type",
                "group",
                "required",
                "options",
                "placeholder",
                "description",
                "unit",
            ],
            delimiter=DELIMITER,
            quoting=csv.QUOTE_MINIMAL,
            # В репозитории принят LF (.gitattributes), а csv.writer по
            # умолчанию пишет CRLF.
            lineterminator="\n",
        )
        writer.writeheader()
        writer.writerows(rows)

    by_group: dict[str, int] = {}
    for row in rows:
        by_group[row["group"]] = by_group.get(row["group"], 0) + 1

    print(f"Записано: {OUTPUT}")
    print(f"Полей: {len(rows)}, обязательных: {sum(1 for r in rows if r['required'] == 'true')}")
    for group in GROUPS:
        print(f"  {by_group.get(group, 0):3d}  {group}")


if __name__ == "__main__":
    main()
